// Optional development-only test. Run against tests/webmail.php --serve, never real accounts.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
    const endpoint = process.argv[2];
    if (!endpoint || !/^http:\/\/127\.0\.0\.1:\d+(?:\/[A-Za-z0-9_-]+)*\/?$/.test(endpoint)) throw new Error('Use the isolated PHP fixture URL.');
    const out = process.env.WEBMAIL_SCREENSHOTS || '/tmp';
    fs.mkdirSync(out, {recursive:true});
    const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
    const context = await browser.newContext({viewport:{width:1440,height:1000}});
    const page = await context.newPage(), errors = [], external = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    await page.route('**/*', route => {
        const url=route.request().url();
        if (!url.startsWith(endpoint) && !url.startsWith('data:')) {external.push(url);return route.abort();}
        return route.continue();
    });
    try {
        await page.goto(endpoint);
        await page.screenshot({path:path.join(out,'login.png')});
        await page.getByLabel('Benutzername',{exact:true}).fill('alice');
        await page.getByLabel('Passwort',{exact:true}).fill('fixture-password-1234');
        await page.getByRole('button',{name:'Anmelden',exact:true}).click();
        await page.locator('tr.msg-row').first().waitFor();
        const originalOrder=await page.locator('#tableHead [data-column-key]').evaluateAll(els=>els.map(el=>el.dataset.columnKey));
        await page.locator('#columnsBtn').click();
        const reorderedSave=page.waitForResponse(response=>response.url().endsWith('/api.php/webmail/settings')&&response.request().method()==='PUT'&&response.status()===200);
        await page.locator('#columnsMenu [data-column-key="date"] .column-grip').dragTo(page.locator('#columnsMenu [data-column-key="message"]'),{targetPosition:{x:20,y:3}});
        await reorderedSave;
        await page.reload();
        await page.locator('tr.msg-row').first().waitFor();
        assert.deepEqual(await page.locator('#tableHead [data-column-key]').evaluateAll(els=>els.map(el=>el.dataset.columnKey)),['date',...originalOrder.filter(key=>key!=='date')]);
        await page.locator('#columnsBtn').click();
        const restoredSave=page.waitForResponse(response=>response.url().endsWith('/api.php/webmail/settings')&&response.request().method()==='PUT'&&response.status()===200);
        await page.getByRole('button',{name:'Empfangen nach unten',exact:true}).click();
        await restoredSave;
        await page.screenshot({path:path.join(out,'column-order-menu.png')});
        await page.locator('#columnsBtn').click();
        assert.deepEqual(await page.locator('#tableHead [data-column-key]').evaluateAll(els=>els.map(el=>el.dataset.columnKey)),originalOrder);
        console.log('ok - Column drag-and-drop persisted through API and page reload; arrows restore order');
        await page.screenshot({path:path.join(out,'initial-mail.png')});
        await page.locator('tr.msg-row').nth(1).locator('.subject').click({position:{x:20,y:8}});
        await page.locator('#bodyBox pre').waitFor();
        assert.equal(await page.locator('#htmlFrame').count(),0,'Plaintext is the default preview');
        await page.getByRole('button',{name:'HTML',exact:true}).click();
        await page.locator('#htmlFrame').waitFor();
        assert.match(await page.frameLocator('#htmlFrame').locator('body').innerText(), /Guten Tag/);
        assert.equal(await page.evaluate(()=>window.pwned), undefined);
        assert.deepEqual(external, []);
        await page.screenshot({path:path.join(out,'mail.png')});
        await page.getByRole('button',{name:'Plaintext',exact:true}).click();
        assert.match(await page.locator('#bodyBox').innerText(),/Anhänge/);
        await page.getByRole('button',{name:'Header',exact:true}).click();
        assert.match(await page.locator('#headerRaw').innerText(), /Message-ID/i);
        await page.locator('#headersDialog [data-close]').click();
        const download = page.waitForEvent('download');
        await page.locator('.attachment').first().click();
        const attachment=await download;
        assert(!attachment.suggestedFilename().includes('/'));
        console.log('ok - Login, HTML/Plaintext, Header, Attachments, XSS/isolation');
        await page.getByRole('button',{name:'⚙ Einstellungen',exact:true}).click();
        await page.locator('#accountForm').waitFor();
        assert.equal(await page.locator('[name="imap_password"]').inputValue(),'');
        await page.locator('[name="label"]').fill('Browser QA mailbox');
        for (const button of await page.locator('[data-remove-identity]').all()) await button.click();
        await page.getByRole('button',{name:'＋ Identität hinzufügen',exact:true}).click();
        await page.locator('[name="identity.0.display_name"]').fill('Browser Test');
        await page.locator('[name="identity.0.from_address"]').fill('reader@example.test');
        await page.locator('[name="identity.0.envelope_from"]').fill('bounce@example.test');
        await page.locator('[name="identity.0.signature.plain_text"]').fill('Viele Grüße');
        await page.getByRole('button',{name:'Einstellungen speichern',exact:true}).click();
        await page.getByRole('heading',{name:'Postfach: Browser QA mailbox',exact:true}).waitFor();
        await page.getByRole('button',{name:'Ansicht & Performance',exact:true}).click();
        await page.locator('[name="density"]').selectOption('comfortable');
        await page.locator('[name="pageSize"]').fill('100');
        await page.locator('#preferencesForm button').click();
        await page.screenshot({path:path.join(out,'preferences.png')});
        await page.getByRole('button',{name:'← Zurück zum Postfach',exact:true}).click();
        await page.locator('tr.msg-row').first().waitFor();
        const splitter=await page.locator('#splitSidebar').boundingBox();
        const before=(await page.locator('#sidebar').boundingBox()).width;
        await page.mouse.move(splitter.x+4,splitter.y+160);await page.mouse.down();await page.mouse.move(splitter.x+64,splitter.y+160);await page.mouse.up();
        assert((await page.locator('#sidebar').boundingBox()).width>before+20);
        await page.getByRole('button',{name:'Erweiterte Suche',exact:true}).click();
        await page.getByLabel('Von enthält',{exact:true}).fill('Jörg');
        await page.getByRole('button',{name:'Suchen',exact:true}).click();
        await page.waitForFunction(()=>document.querySelector('#messageCount').textContent.includes('237'));
        await page.locator('#saveFavoriteBtn').click();
        await page.getByLabel('Name',{exact:true}).fill('Jörg – lokal');
        await page.locator('#favoriteForm button[type="submit"], #favoriteForm button.btn.accent').click();
        await page.locator('#favoriteDialog').waitFor({state:'hidden'});
        await page.reload();
        await page.locator('[data-favorite]').filter({hasText:'Jörg – lokal'}).first().waitFor();
        await page.locator('.folder-row').filter({hasText:'Large'}).click();
        await page.waitForFunction(()=>document.querySelector('#messageCount').textContent.includes('50000'),{},{timeout:60000});
        const wrap=page.locator('#messageTableWrap');
        await wrap.evaluate(el=>el.scrollTop=el.scrollHeight);
        await page.waitForFunction(()=>document.querySelector('#messageCount').textContent.startsWith('200'));
        assert(await page.locator('tr.msg-row').count()<=110);
        await page.screenshot({path:path.join(out,'large-folder.png')});
        console.log('ok - Settings, send-as, preferences, resizer, search, favorites, 50k lazy/virtual list');
        await page.locator('.folder-row').filter({hasText:'INBOX'}).click();
        await page.locator('tr.msg-row').nth(1).locator('.subject').click({position:{x:20,y:8}});
        await page.getByRole('button',{name:'HTML',exact:true}).click();
        await page.locator('#htmlFrame').waitFor();
        await page.setViewportSize({width:390,height:844});
        await page.screenshot({path:path.join(out,'mobile.png')});
        await page.locator('#backToList').click();
        assert(await page.locator('#listPane').isVisible());
        await page.setViewportSize({width:1440,height:1000});
        // An old user's delayed save and queued save must not affect the next session.
        let heldSave, saveCount=0;
        await page.route('**/api.php/webmail/settings', route=>{
            if(route.request().method()==='PUT'){++saveCount;heldSave=route;return;}
            return route.continue();
        });
        await page.evaluate(async()=>{
            const module=await import(document.body.dataset.basePath+'/assets/js/state.js');
            module.state.preferences.pageSize=21;
            module.savePreferences().catch(()=>{});
            module.state.preferences.pageSize=22;
            window.queuedSave=module.savePreferences().catch(()=>{});
        });
        for(let i=0;i<100&&!heldSave;i++)await page.waitForTimeout(10);
        assert(heldSave,'First preference save is held before user switch');
        await page.locator('#appMenuBtn').click();await page.locator('[data-action="logout"]').click();
        await page.getByLabel('Benutzername',{exact:true}).fill('bob');
        await page.getByLabel('Passwort',{exact:true}).fill('fixture-password-1234');
        await page.getByRole('button',{name:'Anmelden',exact:true}).click();
        await page.locator('#messageBody').getByText('Richte in den Einstellungen dein erstes Postfach ein.').waitFor();
        await heldSave.fulfill({status:401,contentType:'application/json',body:JSON.stringify({ok:false,data:null,error:{code:'unauthorized',message:'Expired old session'}})});
        await page.evaluate(()=>window.queuedSave);
        assert.equal(saveCount,1,'Queued save of prior user was discarded');
        assert.equal(await page.locator('#sessionUser').textContent(),'bob');
        assert(await page.locator('#app').isVisible(),'Late 401 cannot log out the new user');
        assert.equal(await page.evaluate(async()=>{const r=await fetch(new URL('./api.php/webmail/settings',document.baseURI));return (await r.json()).data.pageSize}),100);
        console.log('ok - Delayed responses and queued writes isolated across user switch');
        assert.equal(await page.locator('.mailbox-title').count(),0);
        assert.equal(await page.locator('#previewContent').innerText(),'Dein Postfach\nWähle eine Nachricht aus.');
        await page.screenshot({path:path.join(out,'empty-account.png')});
        assert.deepEqual(errors, []);
        assert.deepEqual(external, []);
        assert(!requests.some(url=>/sync\/(start|advance)/.test(url)));
        console.log('ok - Responsive view, logout/user separation, no IMAP on reading, no browser errors or remote requests');
    } catch(error) {
        await page.screenshot({path:path.join(out,'failure.png')});
        console.error('Browser errors:',errors);
        throw error;
    } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
