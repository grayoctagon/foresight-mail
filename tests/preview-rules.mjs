import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../public/assets/js/preview-rules.js', import.meta.url), 'utf8');
const {senderTargets,previewMode,togglePreviewRule,previewWarning} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const message = {from:{email:'Michael@Domain.at'},hasHtml:true};
assert.equal(previewMode({},message),'text');
assert.equal(previewMode({previewMode:'html'},message),'html');
assert.equal(previewMode({previewMode:'html'},{...message,hasHtml:false}),'text');
assert.deepEqual(senderTargets(' Michael@BÜCHER.at '),{address:'michael@xn--bcher-kva.at',domain:'xn--bcher-kva.at'});
for(const address of ['',null,'<michael@domain.at>','a@domain.at/path','a@domain.at:443','a@@domain.at','a@domain.at\nX:evil','a@domain.at.evil/','a@localhost']) assert.equal(senderTargets(address),null,address);
let rules=[{type:'domain',value:'domain.at',mode:'html'}];
assert.equal(previewMode({previewMode:'text',previewRules:rules},message),'html');
assert.equal(previewMode({previewRules:rules},{...message,from:{email:'michael@sub.domain.at'}}),'text');
assert.equal(previewMode({previewRules:rules},{...message,from:{email:'michael@domain.at.evil'}}),'text');
rules=togglePreviewRule(rules,'address','michael@domain.at','text');
assert.equal(previewMode({previewRules:rules},message),'text');
rules=togglePreviewRule(rules,'address','michael@domain.at','html');
assert.equal(rules.filter(r=>r.type==='address').length,1);
assert.equal(previewMode({previewRules:rules},message),'html');
rules=togglePreviewRule(rules,'address','michael@domain.at','html');
assert.equal(rules.filter(r=>r.type==='address').length,0);
assert.equal(rules.length,1);
assert.equal(previewMode({previewRules:rules},message),'html');
assert.match(previewWarning,/gefälscht/);
assert.match(previewWarning,/externe Bilder nicht frei/);
console.log('ok - Text default, IDN/case normalization, exact address/domain precedence, no suffix/subdomain matching, replacement/removal, spoofing warning');
